#!/usr/bin/env bash
# Kimi K3 B300 vLLM recipe derived from the InferenceX B300 submission.
set -euo pipefail
cd "$(dirname "$0")"
# shellcheck source=/dev/null
source ./common_b300.sh

if [[ ! -f "$MODEL_KIMI_K3/config.json" ]]; then
  echo "missing $MODEL_KIMI_K3/config.json" >&2
  exit 1
fi

NAME=kimi-k3-b300-vllm
MOONCAKE_NAME=kimi-k3-mooncake-master
PORT="${VLLM_PORT:-8888}"
MODEL_IN_CONTAINER=/scratch/models/Kimi-K3
SERVED_MODEL_NAME="${SERVED_MODEL_NAME:-moonshotai/Kimi-K3}"
RESTART_POLICY="${RESTART_POLICY:-unless-stopped}"
MOONCAKE_CONFIG="$(pwd)/kimi_k3_mooncake_config.json"
ENABLE_MOONCAKE="${ENABLE_MOONCAKE:-0}"
DCP_SIZE="${DCP_SIZE:-8}"
DCP_COMM_BACKEND="${DCP_COMM_BACKEND:-a2a}"
MAX_NUM_SEQS="${MAX_NUM_SEQS:-140}"
# Research knob, unset in production. Shrinking the KV pool moves the prefix
# cache contention regime down to a team count that can be swept in minutes
# instead of hours; retention policy depends on pool size only through the
# pool-to-working-set ratio, so the comparison is unaffected.
NUM_GPU_BLOCKS_OVERRIDE="${NUM_GPU_BLOCKS_OVERRIDE:-}"
# Optional bind-mount of the same admission rule used on SGLang. The file is
# generated by research/peer-agent-serving/patch_vllm_cohort.py. Unset = stock
# vLLM, which is the first of the two-step portability measurement.
VLLM_BLOCK_POOL_PATCH="${VLLM_BLOCK_POOL_PATCH:-}"
COHORT_CONTROL_DIR="${COHORT_CONTROL_DIR:-/tmp/cohort}"
CAPTURE_SIZES=$(
  python3 - <<'PY'
import json
print(json.dumps([*range(1, 129), 256, 512, 1024, 2048, 4096, 8192]))
PY
)
ATTENTION_CONFIG='{"mla_prefill_backend":"TRTLLM_RAGGED","use_prefill_query_quantization":true}'
COMPILATION_CONFIG=$(printf '{"cudagraph_mode":"FULL_AND_PIECEWISE","cudagraph_capture_sizes":%s}' "$CAPTURE_SIZES")
KV_TRANSFER_CONFIG='{"kv_connector":"MooncakeStoreConnector","kv_role":"kv_both","kv_load_failure_policy":"recompute","kv_connector_extra_config":{"load_async":true,"lookup_async":true,"enable_offload":false}}'
DOCKER_ENV_ARGS=()
VLLM_KV_ARGS=()
VLLM_DCP_ARGS=(--decode-context-parallel-size "$DCP_SIZE")
if [[ "$DCP_SIZE" != "1" ]]; then
  VLLM_DCP_ARGS+=(--dcp-comm-backend "$DCP_COMM_BACKEND")
fi
VLLM_CACHE_ARGS=()
if [[ -n "$NUM_GPU_BLOCKS_OVERRIDE" ]]; then
  VLLM_CACHE_ARGS+=(--num-gpu-blocks-override "$NUM_GPU_BLOCKS_OVERRIDE")
fi

mkdir -p "$LOGDIR"
docker rm -f "$NAME" "$MOONCAKE_NAME" >/dev/null 2>&1 || true
if [[ "$ENABLE_MOONCAKE" == "1" ]]; then
  docker run -d --name "$MOONCAKE_NAME" --restart "$RESTART_POLICY" --init \
    --gpus all \
    --network host \
    --entrypoint mooncake_master \
    "$VLLM_KIMI_K3_IMAGE" \
    --port 50051

  for _ in $(seq 1 30); do
    if (echo >/dev/tcp/127.0.0.1/50051) >/dev/null 2>&1; then
      break
    fi
    if ! docker inspect -f '{{.State.Running}}' "$MOONCAKE_NAME" 2>/dev/null | grep -qx true; then
      docker logs "$MOONCAKE_NAME" >&2
      exit 1
    fi
    sleep 1
  done
  if ! (echo >/dev/tcp/127.0.0.1/50051) >/dev/null 2>&1; then
    echo "Mooncake master did not listen on port 50051" >&2
    docker logs "$MOONCAKE_NAME" >&2
    exit 1
  fi
  DOCKER_ENV_ARGS+=(
    -e MOONCAKE_CONFIG_PATH=/etc/vllm/mooncake_store.json
    -v "$MOONCAKE_CONFIG:/etc/vllm/mooncake_store.json:ro"
  )
  VLLM_KV_ARGS+=(--kv-transfer-config "$KV_TRANSFER_CONFIG")
fi

if [[ -n "$VLLM_BLOCK_POOL_PATCH" ]]; then
  if [[ ! -f "$VLLM_BLOCK_POOL_PATCH" ]]; then
    echo "missing VLLM_BLOCK_POOL_PATCH=$VLLM_BLOCK_POOL_PATCH" >&2
    exit 1
  fi
  VLLM_BP=$(docker run --rm --entrypoint python3 "$VLLM_KIMI_K3_IMAGE" -c \
    "import os,vllm; print(os.path.join(os.path.dirname(vllm.__file__),'v1/core/block_pool.py'))")
  mkdir -p "$COHORT_CONTROL_DIR"
  DOCKER_ENV_ARGS+=(
    -e COHORT_CONTROL="$COHORT_CONTROL_DIR/control.json"
    -v "$COHORT_CONTROL_DIR:$COHORT_CONTROL_DIR:ro"
    -v "$VLLM_BLOCK_POOL_PATCH:$VLLM_BP:ro"
  )
  echo "cohort patch $VLLM_BLOCK_POOL_PATCH -> $VLLM_BP"
fi

docker run -d --name "$NAME" --restart "$RESTART_POLICY" --init \
  --gpus all \
  --network host \
  --ipc=host \
  -e PYTHONHASHSEED=0 \
  "${DOCKER_ENV_ARGS[@]}" \
  -v "$NVME/models:/scratch/models" \
  -v "$NVME/cache:/root/.cache/huggingface" \
  -v "$NVME/logs:$LOGDIR" \
  --entrypoint vllm \
  "$VLLM_KIMI_K3_IMAGE" \
  serve "$MODEL_IN_CONTAINER" \
    --served-model-name "$SERVED_MODEL_NAME" \
    --host 0.0.0.0 \
    --port "$PORT" \
    --tensor-parallel-size 8 \
    "${VLLM_DCP_ARGS[@]}" \
    --max-num-seqs "$MAX_NUM_SEQS" \
    --gpu-memory-utilization 0.90 \
    --max-num-batched-tokens 16384 \
    --trust-remote-code \
    --language-model-only \
    --reasoning-parser kimi_k3 \
    --enable-auto-tool-choice \
    --tool-call-parser kimi_k3 \
    --load-format fastsafetensors \
    --moe-backend auto \
    --no-enable-flashinfer-autotune \
    --enable-cumem-allocator \
    --enable-prefix-caching \
    --prefix-match-unit 128 \
    --kv-cache-dtype fp8 \
    --stream-interval 10 \
    --attention-backend TOKENSPEED_MLA \
    --attention-config "$ATTENTION_CONFIG" \
    --compilation-config "$COMPILATION_CONFIG" \
    --disable-uvicorn-access-log \
    "${VLLM_CACHE_ARGS[@]}" \
    "${VLLM_KV_ARGS[@]}"

echo "started $NAME on :$PORT image=$VLLM_KIMI_K3_IMAGE"
echo "model=$MODEL_IN_CONTAINER served_model_name=$SERVED_MODEL_NAME tp=8 dcp=$DCP_SIZE/$DCP_COMM_BACKEND max_seqs=$MAX_NUM_SEQS mooncake=$ENABLE_MOONCAKE"
